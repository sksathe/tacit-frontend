import { mkdirSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const apiBase = (process.env.VITE_API_BASE_URL || process.env.VITE_API_URL || "").trim();

const generatedDir = join(root, "src", "generated");
mkdirSync(generatedDir, { recursive: true });

writeFileSync(
  join(generatedDir, "apiBase.ts"),
  `// Generated by scripts/ensure-build-env.mjs — do not edit\nexport const BUILD_TIME_API_BASE_URL = ${JSON.stringify(apiBase)};\n`,
);

writeFileSync(join(root, "public", "config.json"), JSON.stringify({ apiBaseUrl: apiBase }, null, 2));

console.log(
  `[build] VITE_API_BASE_URL=${apiBase || "(empty — set on frontend service and redeploy, or configure /api rewrite)"}`,
);

if (process.env.RENDER === "true" && !apiBase) {
  console.warn(
    "[build] WARNING: RENDER build without VITE_API_BASE_URL. API calls will use same-origin /api/* — you must add a Render rewrite to your backend.",
  );
}
